//! 扫描 `#[contribute]` 标注并生成统一注册函数 `register_rml_contributions`。

use std::fs;
use std::path::{Path, PathBuf};

use syn::{File, Item};

use crate::build::BuildError;

/// build.rs 扫描到的 `#[contribute]` 注册项。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ContributionRegistrar {
    /// 如 `crate::cases::counter_case`
    pub module_path: String,
    /// 如 `countercase`（对应 `__rml_register_countercase`）
    pub register_suffix: String,
}

/// 根据扫描结果生成 `rml_contributions.rs`。
pub fn generate(registrars: &[ContributionRegistrar], output_dir: &Path) -> Result<(), BuildError> {
    let generated_dir = output_dir.join("rml_generated");
    fs::create_dir_all(&generated_dir).map_err(|e| BuildError {
        message: format!("failed to create {}: {}", generated_dir.display(), e),
    })?;

    let mut body = String::from(
        "// Auto-generated by RML build.rs — do not edit.\n\
         // Collects all `#[contribute]` structs and calls their `__rml_register_*` hooks.\n\n\
         #[allow(dead_code, unused_imports)]\n\
         pub fn register_rml_contributions(cx: &mut gpui::App) {\n\
             use gpui::BorrowAppContext;\n",
    );

    if registrars.is_empty() {
        body.push_str("    let _ = cx;\n");
    } else {
        for reg in registrars {
            body.push_str(&format!(
                "    {}::__rml_register_{}(cx);\n",
                reg.module_path, reg.register_suffix
            ));
        }
    }

    body.push_str("}\n");

    let out_path = generated_dir.join("rml_contributions.rs");
    fs::write(&out_path, body).map_err(|e| BuildError {
        message: format!("write {}: {}", out_path.display(), e),
    })?;

    Ok(())
}

/// 从 `.rs` 源文件解析 `#[contribute]` struct，返回注册元信息。
pub fn parse_contribution_registrars(
    rs_path: &Path,
    scan_root: &Path,
) -> Result<Vec<ContributionRegistrar>, ()> {
    let source = fs::read_to_string(rs_path).map_err(|_| ())?;
    let file: File = syn::parse_str(&source).map_err(|_| ())?;

    let module_path = module_path_from_file(scan_root, rs_path).ok_or(())?;

    let mut out = Vec::new();
    for item in &file.items {
        let Item::Struct(s) = item else {
            continue;
        };
        let has_contribute = s.attrs.iter().any(|a| {
            a.path()
                .get_ident()
                .is_some_and(|id| id == "contribute")
                || a.path().segments.last().is_some_and(|s| s.ident == "contribute")
        });
        if !has_contribute {
            continue;
        }
        out.push(ContributionRegistrar {
            module_path: module_path.clone(),
            register_suffix: s.ident.to_string().to_lowercase(),
        });
    }
    Ok(out)
}

/// `src/cases/foo.rml.rs` → `crate::cases::foo`
fn module_path_from_file(scan_root: &Path, file: &Path) -> Option<String> {
    let rel = file.strip_prefix(scan_root).ok()?;
    let rel_str = rel.to_str()?;
    let without_ext = rel_str
        .strip_suffix(".rml.rs")
        .or_else(|| rel_str.strip_suffix(".rs"))?;
    let mod_path = without_ext.replace('\\', "/").replace('/', "::");
    Some(format!("crate::{mod_path}"))
}

/// 递归扫描 `scan_dirs` 下所有 `.rs` 文件中的 `#[contribute]`。
pub fn scan_contribution_registrars(scan_dirs: &[PathBuf]) -> Vec<ContributionRegistrar> {
    let mut registrars = Vec::new();
    for dir in scan_dirs {
        if !dir.exists() {
            continue;
        }
        for entry in walkdir::WalkDir::new(dir).into_iter().filter_map(|e| e.ok()) {
            let path = entry.path();
            if !path.is_file() {
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            if let Ok(mut found) = parse_contribution_registrars(path, dir) {
                registrars.append(&mut found);
            }
        }
    }
    registrars.sort_by(|a, b| {
        a.module_path
            .cmp(&b.module_path)
            .then_with(|| a.register_suffix.cmp(&b.register_suffix))
    });
    registrars.dedup_by(|a, b| {
        a.module_path == b.module_path && a.register_suffix == b.register_suffix
    });
    registrars
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_path_from_rml_rs() {
        let root = Path::new("src");
        let file = Path::new("src/cases/counter_case.rml.rs");
        assert_eq!(
            module_path_from_file(root, file).as_deref(),
            Some("crate::cases::counter_case")
        );
    }
}
