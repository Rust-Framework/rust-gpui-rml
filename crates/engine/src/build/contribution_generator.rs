//! 扫描 `#[contribute]` 并生成按 `host_id` 路由的注册函数 `register_rml_contributions_for(cx, host_id)`。
//!
//! **设计**：
//! - `#[contribute(host_id = "...", ...)]` 的 `host_id` 字符串字面量在 build.rs 扫描时解析
//! - build.rs 按 `host_id` 分组，生成 `match host_id { "demo.shell" => { ... } _ => {} }`
//! - host 在 `on_loaded` 中手动调用 `bootstrap_host_contributions(cx, id)`
//!   回调此处的 `register_rml_contributions_for(cx, host_id)`，按 host_id 路由调用 `__rml_register_*`
//! - host 未注册时 `register` 直接 drop 贡献（warn），要求 host `on_loaded`
//!   必须先 `registry.add(host)` 再调用 `bootstrap_host_contributions` 触发贡献注册

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use syn::{File, Item};

use crate::build::BuildError;

/// build.rs 扫描到的 `#[contribute]` 注册项。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ContributionRegistrar {
    /// 如 `crate::cases::counter_case`
    pub module_path: String,
    /// 如 `countercase`（对应 `__rml_register_countercase`）
    pub register_suffix: String,
    /// 如 `demo.shell`（从 `#[contribute(host_id = "demo.shell")]` 解析）
    pub host_id: String,
}

/// 根据扫描结果生成 `rml_contributions.rs`。
///
/// 生成 `register_rml_contributions_for(cx, host_id)`，按 host_id match 调用对应 `__rml_register_*`。
/// 同时生成 `#[ctor::ctor]` 安装该函数到 `CONTRIBUTION_BOOTSTRAP` 全局指针。
pub fn generate(
    contributions: &[ContributionRegistrar],
    output_dir: &Path,
) -> Result<(), BuildError> {
    let generated_dir = output_dir.join("rml_generated");
    fs::create_dir_all(&generated_dir).map_err(|e| BuildError {
        message: format!("failed to create {}: {}", generated_dir.display(), e),
    })?;

    // 按 host_id 分组（BTreeMap 保证输出稳定）
    let mut by_host: BTreeMap<&str, Vec<&ContributionRegistrar>> = BTreeMap::new();
    for c in contributions {
        by_host.entry(&c.host_id).or_default().push(c);
    }

    let mut body = String::from(
        "// Auto-generated by RML build.rs — do not edit.\n\
         // 按 host_id 路由调用所有 `#[contribute(host_id = \"...\")]` 的 `__rml_register_*` 函数。\n\n\
         #[allow(dead_code, unused_imports)]\n\
         pub fn register_rml_contributions_for(cx: &mut gpui::App, host_id: &str) {\n\
             match host_id {\n",
    );

    for (host_id, regs) in &by_host {
        body.push_str(&format!("        {:?} => {{\n", host_id));
        for reg in regs {
            body.push_str(&format!(
                "            {}::__rml_register_{}(cx);\n",
                reg.module_path, reg.register_suffix
            ));
        }
        body.push_str("        }\n");
    }

    body.push_str("        _ => {}\n    }\n}\n\n");

    body.push_str(
        "#[rml_core::ctor::ctor]\n\
         fn __rml_install_contribution_bootstrap() {\n\
             rml_app::contribution::install_contribution_bootstrap(register_rml_contributions_for);\n\
         }\n",
    );

    let out_path = generated_dir.join("rml_contributions.rs");
    fs::write(&out_path, body).map_err(|e| BuildError {
        message: format!("write {}: {}", out_path.display(), e),
    })?;

    Ok(())
}

fn has_attr(attrs: &[syn::Attribute], name: &str) -> bool {
    attrs.iter().any(|a| {
        a.path()
            .get_ident()
            .is_some_and(|id| id == name)
            || a.path().segments.last().is_some_and(|s| s.ident == name)
    })
}

/// 从 `#[contribute(host_id = "...", ...)]` 解析 `host_id` 字符串字面量。
///
/// `host_id` 必须是字符串字面量（与 `crates/macros/src/contribute.rs::host_id_tokens` 对齐）。
/// 缺失或非字符串字面量时返回 `None`，调用方按需跳过或告警。
fn parse_host_id(attrs: &[syn::Attribute]) -> Option<String> {
    use syn::parse::Parser;
    use syn::punctuated::Punctuated;
    use syn::Token;
    for attr in attrs {
        if !attr.path().is_ident("contribute") {
            continue;
        }
        let nested = attr.meta.require_list().ok()?;
        let parsed: Punctuated<syn::Meta, Token![,]> = Punctuated::parse_terminated
            .parse2(nested.tokens.clone())
            .ok()?;
        for meta in parsed {
            if let syn::Meta::NameValue(nv) = meta {
                if nv.path.is_ident("host_id") {
                    if let syn::Expr::Lit(syn::ExprLit {
                        lit: syn::Lit::Str(s),
                        ..
                    }) = nv.value
                    {
                        return Some(s.value());
                    }
                }
            }
        }
    }
    None
}

/// 从 `.rs` 源文件解析 `#[contribute]` struct，返回注册元信息。
///
/// 跳过无 `host_id` 或 `host_id` 非字符串字面量的项（`#[contribute]` 宏会编译报错，
/// build.rs 扫描期跳过即可，不重复报错）。
pub fn parse_contribution_registrars(
    rs_path: &Path,
    scan_root: &Path,
) -> Option<Vec<ContributionRegistrar>> {
    let source = fs::read_to_string(rs_path).ok()?;
    let file: File = syn::parse_str(&source).ok()?;

    let module_path = module_path_from_file(scan_root, rs_path)?;

    let mut out = Vec::new();
    for item in &file.items {
        let Item::Struct(s) = item else {
            continue;
        };
        if !has_attr(&s.attrs, "contribute") {
            continue;
        }
        let Some(host_id) = parse_host_id(&s.attrs) else {
            // `#[contribute]` 宏自身会在编译期报错（missing host_id），
            // build.rs 扫描期跳过即可。
            continue;
        };
        out.push(ContributionRegistrar {
            module_path: module_path.clone(),
            register_suffix: s.ident.to_string().to_lowercase(),
            host_id,
        });
    }
    Some(out)
}

/// `src/cases/foo.rml.rs` → `crate::cases::foo`
fn module_path_from_file(scan_root: &Path, file: &Path) -> Option<String> {
    let rel = file.strip_prefix(scan_root).ok()?;
    let rel_str = rel.to_str()?;
    let without_ext = rel_str
        .strip_suffix(".rml.rs")
        .or_else(|| rel_str.strip_suffix(".rs"))?;
    let mod_path = without_ext.replace('\\', "/").replace('/', "::");
    Some(format!("crate::{mod_path}"))
}

fn dedup_contributions(contributions: &mut Vec<ContributionRegistrar>) {
    contributions.sort_by(|a, b| {
        a.host_id
            .cmp(&b.host_id)
            .then_with(|| a.module_path.cmp(&b.module_path))
            .then_with(|| a.register_suffix.cmp(&b.register_suffix))
    });
    contributions.dedup_by(|a, b| {
        a.host_id == b.host_id
            && a.module_path == b.module_path
            && a.register_suffix == b.register_suffix
    });
}

/// 递归扫描 `scan_dirs` 下所有 `.rs` 文件中的 `#[contribute]`。
pub fn scan_contribution_registrars(
    scan_dirs: &[PathBuf],
) -> Vec<ContributionRegistrar> {
    let mut contributions = Vec::new();
    for dir in scan_dirs {
        if !dir.exists() {
            continue;
        }
        for entry in walkdir::WalkDir::new(dir).into_iter().filter_map(|e| e.ok()) {
            let path = entry.path();
            if !path.is_file() {
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            if let Some(mut found) = parse_contribution_registrars(path, dir) {
                contributions.append(&mut found);
            }
        }
    }
    dedup_contributions(&mut contributions);
    contributions
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_path_from_rml_rs() {
        let root = Path::new("src");
        let file = Path::new("src/cases/counter_case.rml.rs");
        assert_eq!(
            module_path_from_file(root, file).as_deref(),
            Some("crate::cases::counter_case")
        );
    }

    #[test]
    fn parse_host_id_from_simple_attr() {
        use syn::parse::Parser;
        // `#[contribute(host_id = "demo.shell")]`
        let attrs = syn::Attribute::parse_outer
            .parse_str("#[contribute(host_id = \"demo.shell\")]")
            .expect("parse attr");
        assert_eq!(parse_host_id(&attrs).as_deref(), Some("demo.shell"));
    }

    #[test]
    fn parse_host_id_from_multi_field_attr() {
        use syn::parse::Parser;
        // `#[contribute(host_id = "demo.shell", id = "samples", order = 0)]`
        let source = "#[contribute(host_id = \"demo.shell\", id = \"samples\", order = 0)]";
        let attrs = syn::Attribute::parse_outer
            .parse_str(source)
            .expect("parse attr");
        assert_eq!(parse_host_id(&attrs).as_deref(), Some("demo.shell"));
    }

    #[test]
    fn parse_host_id_missing_returns_none() {
        use syn::parse::Parser;
        let attrs = syn::Attribute::parse_outer
            .parse_str("#[contribute(id = \"samples\")]")
            .expect("parse attr");
        assert!(parse_host_id(&attrs).is_none());
    }

    #[test]
    fn parse_contribution_registrars_extracts_host_id() {
        // 写入临时文件扫描
        let tmp = std::env::temp_dir().join("rml_contribution_gen_test.rs");
        let source = r#"
            use rml::prelude::*;
            #[contribute(host_id = "demo.shell", id = "counter", name = "counter")]
            #[component]
            #[derive(Default)]
            pub struct CounterCase;
        "#;
        std::fs::write(&tmp, source).unwrap();
        let root = tmp.parent().unwrap();
        let regs = parse_contribution_registrars(&tmp, root).expect("parse ok");
        assert_eq!(regs.len(), 1);
        assert_eq!(regs[0].host_id, "demo.shell");
        assert_eq!(regs[0].register_suffix, "countercase");
        let _ = std::fs::remove_file(&tmp);
    }

    #[test]
    fn generate_outputs_match_on_host_id() {
        let regs = vec![
            ContributionRegistrar {
                module_path: "crate::cases::counter_case".into(),
                register_suffix: "countercase".into(),
                host_id: "demo.shell".into(),
            },
            ContributionRegistrar {
                module_path: "crate::cases::button_case".into(),
                register_suffix: "buttoncase".into(),
                host_id: "demo.shell".into(),
            },
            ContributionRegistrar {
                module_path: "crate::cases::other".into(),
                register_suffix: "other".into(),
                host_id: "demo.activity".into(),
            },
        ];
        let tmp = std::env::temp_dir().join("rml_gen_out_test");
        std::fs::create_dir_all(&tmp).unwrap();
        generate(&regs, &tmp).expect("generate ok");
        let out = std::fs::read_to_string(tmp.join("rml_generated/rml_contributions.rs")).unwrap();
        assert!(out.contains("pub fn register_rml_contributions_for(cx: &mut gpui::App, host_id: &str)"));
        assert!(out.contains("\"demo.activity\""));
        assert!(out.contains("\"demo.shell\""));
        assert!(out.contains("crate::cases::counter_case::__rml_register_countercase(cx);"));
        assert!(out.contains("crate::cases::button_case::__rml_register_buttoncase(cx);"));
        assert!(out.contains("crate::cases::other::__rml_register_other(cx);"));
        assert!(out.contains("install_contribution_bootstrap(register_rml_contributions_for);"));
        let _ = std::fs::remove_dir_all(&tmp);
    }
}
