//! 构建期资源处理器
//!
//! 递归扫描 `assets/` 目录,按 `embed` 模式生成资源注册代码到
//! `OUT_DIR/rml_generated/rml_assets.rs`。
//!
//! - **embed=true（嵌入模式）**：每个文件通过 `include_bytes!` 编译期嵌入二进制,
//!   生成 `static RML_ASSETS` 静态表 + `#[ctor::ctor]` 函数在 `main` 之前自动调用
//!   `rml_core::assets::init(AssetSource::Embedded { ... })`。
//! - **embed=false（文件系统模式）**：不嵌入任何字节,仅生成 `#[ctor::ctor]` 函数
//!   调用 `assets::init(AssetSource::Filesystem { root: "..." })`,运行期按需读取磁盘。
//!
//! 运行时通过 `rml_core::assets::load(path)` 查询,路径以相对 `assets/` 的正斜杠形式存储
//! (如 `"i18n/zh-CN.json"`、`"themes/dark.css"`)。

use std::fs;
use std::path::{Path, PathBuf};

use super::BuildError;

/// 资源模式
#[derive(Clone, Copy, PartialEq)]
pub enum AssetMode {
    /// 嵌入：编译期 `include_bytes!` 把字节写入二进制
    Embedded,
    /// 文件系统：运行期从磁盘读取
    Filesystem,
}

/// 资源处理器：扫描目录并按模式生成注册代码
pub struct AssetsProcessor {
    root_dir: PathBuf,
    mode: AssetMode,
}

impl AssetsProcessor {
    pub fn new(root_dir: impl Into<PathBuf>, mode: AssetMode) -> Self {
        let root_dir = root_dir.into();
        // include_bytes! 需要绝对路径(相对生成文件位置解析),故相对 CARGO_MANIFEST_DIR 解析
        let root_dir = if root_dir.is_absolute() {
            root_dir
        } else {
            let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")
                .expect("CARGO_MANIFEST_DIR not set");
            PathBuf::from(manifest_dir).join(root_dir)
        };
        Self { root_dir, mode }
    }

    pub fn root_dir(&self) -> &Path {
        &self.root_dir
    }

    /// 扫描 root_dir,生成资源注册代码到 `OUT_DIR/rml_generated/rml_assets.rs`
    ///
    /// 始终写入文件(即使目录不存在或无资源,输出有效的 ctor 注册代码),
    /// 保证用户 crate 的 `rml::embed_assets!()` 始终可用。
    pub fn generate(&self, output_dir: &Path) -> Result<(), BuildError> {
        let entries = if self.root_dir.exists() {
            self.collect_entries()?
        } else {
            Vec::new()
        };

        let generated_dir = output_dir.join("rml_generated");
        fs::create_dir_all(&generated_dir).map_err(|e| BuildError {
            message: format!(
                "failed to create {}: {}",
                generated_dir.display(),
                e
            ),
        })?;

        let out_path = generated_dir.join("rml_assets.rs");
        let code = self.render_registry(&entries);
        fs::write(&out_path, code).map_err(|e| BuildError {
            message: format!("write {}: {}", out_path.display(), e),
        })?;

        Ok(())
    }

    /// 递归收集目录下所有文件,返回 (相对路径字符串, 绝对路径) 列表
    fn collect_entries(&self) -> Result<Vec<(String, PathBuf)>, BuildError> {
        let mut entries = Vec::new();
        for entry in walkdir::WalkDir::new(&self.root_dir)
            .follow_links(false)
            .into_iter()
            .filter_map(|e| e.ok())
        {
            if !entry.file_type().is_file() {
                continue;
            }
            let abs_path = entry.path().to_path_buf();
            let rel_path = abs_path
                .strip_prefix(&self.root_dir)
                .map_err(|e| BuildError {
                    message: format!(
                        "strip prefix {} from {}: {}",
                        self.root_dir.display(),
                        abs_path.display(),
                        e
                    ),
                })?;
            // 统一使用正斜杠,跨平台一致
            let key = rel_path.to_string_lossy().replace('\\', "/");
            entries.push((key, abs_path.clone()));
            // 文件变化时重新生成
            println!("cargo:rerun-if-changed={}", abs_path.display());
        }
        // 按 key 排序,保证生成代码稳定
        entries.sort_by(|a, b| a.0.cmp(&b.0));
        Ok(entries)
    }

    /// 渲染注册表 Rust 代码
    fn render_registry(&self, entries: &[(String, PathBuf)]) -> String {
        let mut code = String::new();
        code.push_str("// Auto-generated by RML AssetsProcessor. DO NOT EDIT.\n");
        code.push_str("// 包含 #[ctor::ctor] 函数,在 main 之前自动注册资源源到 rml_core::assets。\n\n");

        match self.mode {
            AssetMode::Embedded => {
                // 静态表 + ctor 自动 init
                code.push_str("#[allow(dead_code)]\n");
                code.push_str(
                    "pub static RML_ASSETS: &[(&'static str, &'static [u8])] = &[\n",
                );
                for (key, abs_path) in entries {
                    // include_bytes! 需要字面量路径,使用绝对路径字符串
                    let abs_str = abs_path.to_string_lossy().replace('\\', "\\\\");
                    code.push_str(&format!(
                        "    ({:?}, include_bytes!({:?})),\n",
                        key, abs_str
                    ));
                }
                code.push_str("];\n\n");

                code.push_str("#[rml_core::ctor::ctor]\n");
                code.push_str("fn __rml_assets_auto_init() {\n");
                code.push_str(
                    "    rml_core::assets::init(rml_core::assets::AssetSource::Embedded {\n",
                );
                code.push_str("        entries: RML_ASSETS,\n");
                code.push_str("    });\n");
                code.push_str("}\n");
            }
            AssetMode::Filesystem => {
                // 文件系统模式：仅 ctor init 路径根
                let root_str = self.root_dir.to_string_lossy().replace('\\', "/");
                code.push_str("#[rml_core::ctor::ctor]\n");
                code.push_str("fn __rml_assets_auto_init() {\n");
                code.push_str("    rml_core::assets::init(rml_core::assets::AssetSource::Filesystem {\n");
                code.push_str(&format!("        root: {:?},\n", root_str));
                code.push_str("    });\n");
                code.push_str("}\n");
            }
        }
        code
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write;

    #[test]
    fn collect_and_render_embedded() {
        let tmp = std::env::temp_dir().join("rml_assets_test_embedded");
        let _ = fs::remove_dir_all(&tmp);
        fs::create_dir_all(tmp.join("themes")).unwrap();
        let mut f = fs::File::create(tmp.join("themes/dark.css")).unwrap();
        writeln!(f, ":root {{ --primary: #000; }}").unwrap();
        let mut f = fs::File::create(tmp.join("logo.svg")).unwrap();
        writeln!(f, "<svg/>").unwrap();

        let proc = AssetsProcessor::new(&tmp, AssetMode::Embedded);
        let entries = proc.collect_entries().unwrap();
        let keys: Vec<&String> = entries.iter().map(|(k, _)| k).collect();
        assert!(keys.contains(&&"themes/dark.css".to_string()));
        assert!(keys.contains(&&"logo.svg".to_string()));

        let code = proc.render_registry(&entries);
        assert!(code.contains("\"themes/dark.css\""));
        assert!(code.contains("include_bytes!"));
        assert!(code.contains("#[rml_core::ctor::ctor]"));
        assert!(code.contains("AssetSource::Embedded"));
        assert!(code.contains("RML_ASSETS"));

        let _ = fs::remove_dir_all(&tmp);
    }

    #[test]
    fn render_filesystem_mode() {
        let proc = AssetsProcessor::new("/some/path/assets", AssetMode::Filesystem);
        let code = proc.render_registry(&[]);

        assert!(!code.contains("include_bytes!"));
        assert!(!code.contains("RML_ASSETS"));
        assert!(code.contains("#[rml_core::ctor::ctor]"));
        assert!(code.contains("AssetSource::Filesystem"));
        assert!(code.contains("/some/path/assets"));
    }
}
