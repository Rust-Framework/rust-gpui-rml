//! 代码生成器（核心入口）
//!
//! 将 AST 转换为 Rust 源码字符串（`impl Render for <View>`）。
//! 详见文档 §10.6 代码生成。
//!
//! 生成代码通过 `include!` 注入用户模块，因此：
//! - 全部使用完全限定路径（`gpui::*`、`rml::runtime::*`），避免与用户 import 冲突
//! - 事件回调统一通过 `rml::runtime::event_flow::convert::from_gpui_*` 转换 GPUI 事件 → RML 事件
//! - GPUI 事件监听器（on_click 等）要求元素为 `Stateful<Div>`，需先调用 `.id(...)` 赋予 ID
//!
//! ## 模块职责
//!
//! - `mod.rs`（本文件）：入口 `codegen()` 函数，按根标签分派到 window/observable/render
//! - `node.rs`：节点代码生成（gen_node + gen_element）
//! - `attribute.rs`：属性代码生成（静态/CSS/内联/绑定）
//! - `text.rs`：文本与表达式代码生成（混合文本/插值/i18n）
//! - `model.rs`：Model 字段收集
//! - `render.rs`：`impl Render` 生成
//! - `window.rs`：窗口/对话框 impl 生成（`impl IWindow` / `open`+`close`）
//! - `shell.rs`：窗口外壳包裹（ModernWindowShell / TabWindowShell）
//! - `binding.rs`：双向绑定与字段校验代码生成
//! - `observable.rs`：Observable 版本管理 + 计算属性缓存 + InputState 同步
//! - `event.rs`：事件绑定代码生成（onclick → .on_click 等）
//! - `component.rs`：gpui-component 扩展组件生成（Button/Input 等）
//! - `expr.rs`：表达式解析器（{count + 1} → AST → Rust 代码）

