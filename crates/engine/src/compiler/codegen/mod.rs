    fn codegen_button_root_returns_error() {
        let root = crate::parser::parse("<button></button>").unwrap();
        assert!(codegen(&root, &minimal_ctx()).is_err());
    }

    // ─── 成功路径：各根标签可生成代码 ───

    #[test]
    fn codegen_component_root_succeeds() {
        let root = crate::parser::parse("<component></component>").unwrap();
        let result = codegen(&root, &minimal_ctx());
        assert!(result.is_ok(), "codegen failed: {:?}", result.err());
        let code = result.unwrap();
        // 确认生成代码包含自动生成注释和 impl Render
        assert!(
            code.contains("// Auto-generated by RML compiler. DO NOT EDIT."),
            "expected auto-generated header"
        );
        assert!(
            code.contains("impl gpui::Render for TestView"),
            "expected impl Render for TestView, got snippet: {}",
            code.chars().take(300).collect::<String>()
        );
    }

