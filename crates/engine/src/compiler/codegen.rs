/// 收集 RML 中所有 `model={field}` 绑定的字段名
pub fn collect_model_fields(root: &Node) -> Vec<String> {
    let mut fields = Vec::new();
    if let Node::Element(elem) = root {
        collect_model_fields_recursive(elem, &mut fields);
    }
    fields.sort();
    fields.dedup();
    fields
}

fn collect_model_fields_recursive(elem: &Element, fields: &mut Vec<String>) {
    for directive in &elem.directives {
        if let Directive::Model(field) = directive {
            fields.push(field.clone());
        }
    }
    for child in &elem.children {
        if let Node::Element(child_elem) = child {
            collect_model_fields_recursive(child_elem, fields);
        }
    }
}

/// 生成 `impl Render for <ViewStruct>` 代码块（可能附带 `impl IWindow`）
///
/// RML 根节点必须是 `<window>`、`<modern_window>`、`<tab_window>` 或 `<component>`：
/// - `<window>`/`<modern_window>`：生成 `impl IWindow`（从根节点属性提取 title/width/height）
///   + `impl Render`（使用根节点的子节点作为渲染树）
/// - `<component>`：仅生成 `impl Render`（使用根节点的子节点）
/// - 其他：报错
pub fn codegen(root: &Node, ctx: &CodegenCtx) -> Result<String, CodegenError> {
    let elem = match root {
        Node::Element(e) if tags::is_root_tag(&e.tag) => e,
        _ => {
            return Err(CodegenError {
                message: format!(
                    "root element must be <window>, <modern_window>, <tab_window>, or <component>; got <{}>",
                    root
                ),
            });
        }
    };

    let root_tag = tags::root_tag_lookup(&elem.tag)
        .ok_or_else(|| CodegenError { message: format!("invalid root tag: <{}>", elem.tag) })?;

    let mut out = String::new();
    out.push_str("// Auto-generated by RML compiler. DO NOT EDIT.\n");
    out.push_str("#[allow(unused_imports, unused_variables, non_snake_case, dead_code)]\n\n");

    let shell_wrap = match root_tag {
        tags::RootTag::ModernWindow => ShellWrap::Modern,
        tags::RootTag::TabWindow => ShellWrap::Tab,
        _ => ShellWrap::None,
    };

    let chrome_transparent = matches!(
        root_tag,
        tags::RootTag::ModernWindow | tags::RootTag::TabWindow
    );

    // 1. 窗口类型：生成 impl IWindow（从根节点属性提取配置）
    match root_tag {
        tags::RootTag::Window => {
            out.push_str(&gen_window_impl(elem, ctx, false)?);
            out.push('\n');
        }
        tags::RootTag::ModernWindow | tags::RootTag::TabWindow => {
            out.push_str(&gen_window_impl(elem, ctx, chrome_transparent)?);
            out.push('\n');
        }
        tags::RootTag::Component => {}
    }

    // 2. 生成 impl Render
    out.push_str(&gen_render_impl_from_children(elem, ctx, shell_wrap)?);

    // 3. Phase B-2：生成版本管理方法 + 计算属性包装方法
    //    （与 #[command] 宏注入的 bump_version 调用、#[computed] 宏的重命名配合）
    out.push_str(&gen_observable_impl(ctx));
    out.push('\n');
    out.push_str(&gen_computed_wrappers(ctx));
    out.push('\n');

    // 4. Phase B-3：生成 InputState 惰性初始化方法（供双向绑定使用）
    out.push_str(&gen_input_state_impl(ctx));

    Ok(out)
}

/// 窗口壳包裹类型
enum ShellWrap {
    None,
    Modern,
    Tab,
}

/// 从 `<window>`/`<modern_window>`/`<tab_window>` 根节点生成 `impl IWindow`
///
/// 提取 `title`/`width`/`height` 属性，生成完整的 `impl IWindow` 代码块。
/// `chrome_transparent` 为 true 时生成 `WindowChrome::Transparent`。
fn gen_window_impl(
    elem: &Element,
    ctx: &CodegenCtx,
    chrome_transparent: bool,
) -> Result<String, CodegenError> {
    let view_name = &ctx.view_struct_name;

    // 提取属性（默认值）
    let title = extract_static_attr(elem, "title").unwrap_or_else(|| "RML Window".to_string());
    let width = extract_static_attr(elem, "width")
        .and_then(|s| s.parse::<f32>().ok())
        .unwrap_or(800.0);
    let height = extract_static_attr(elem, "height")
        .and_then(|s| s.parse::<f32>().ok())
        .unwrap_or(600.0);

    let left = extract_static_attr(elem, "left")
        .and_then(|s| s.parse::<f32>().ok());
    let top = extract_static_attr(elem, "top")
        .and_then(|s| s.parse::<f32>().ok());
    let startup = extract_static_attr(elem, "startup");
    let min_width = extract_static_attr(elem, "min_width")
        .and_then(|s| s.parse::<f32>().ok());
    let min_height = extract_static_attr(elem, "min_height")
        .and_then(|s| s.parse::<f32>().ok());

    let extra_methods = gen_window_extra_methods(
        left,
        top,
        startup.as_deref(),
        min_width,
        min_height,
        elem,
    );

    let chrome_method = if chrome_transparent {
        // ModernWindowShell 自绘 TitleBar，需要透明标题栏模式
        // （appears_transparent: true + WindowDecorations::Client）
        "    fn chrome(&self) -> rml_core::window::WindowChrome {\n        rml_core::window::WindowChrome::Transparent\n    }\n"
    } else {
        ""
    };

    let code = format!(
        r#"impl rml_core::window::IWindow for {view_name} {{
    fn title(&self) -> &str {{
        {title:?}
    }}

    fn width(&self) -> gpui::Pixels {{
        gpui::px({width:?})
    }}

    fn height(&self) -> gpui::Pixels {{
        gpui::px({height:?})
    }}
{extra_methods}
{chrome_method}
    fn open(&mut self, cx: &mut gpui::App) {{
        rml_ui::IWindowExt::open_rooted(self, cx);
    }}

    fn handle(&self) -> Option<gpui::AnyWindowHandle> {{
        self.__rml_window_handle
    }}

    fn set_handle(&mut self, handle: gpui::AnyWindowHandle) {{
        self.__rml_window_handle = Some(handle);
    }}
}}"#,
        view_name = view_name,
        title = title,
        width = width,
        height = height,
        extra_methods = extra_methods,
        chrome_method = chrome_method,
    );

    Ok(code)
}

/// 从根节点的子节点生成 `impl Render`
///
/// 单个子节点：直接使用其代码。
/// 多个子节点：包裹在 `gpui::div()` 中，逐个 `.child(...)`。
/// 零子节点：使用 `gpui::div()` 作为占位。
///
/// `is_modern=true` 时（`<modern_window>` 根元素），用 `rml_ui::ModernWindowShell` 包裹
/// 子节点，自动提供 TitleBar/Menu/StatusBar。title 复用 `IWindow::title()`（不重复定义），
/// menu/status_bar 从根元素属性提取。
fn gen_render_impl_from_children(
    elem: &Element,
    ctx: &CodegenCtx,
    shell: ShellWrap,
) -> Result<String, CodegenError> {
    let view_name = &ctx.view_struct_name;
    let mut out = String::new();

    out.push_str(&format!("impl gpui::Render for {} {{\n", view_name));
    out.push_str(
        "    fn render(&mut self, _window: &mut gpui::Window, cx: &mut gpui::Context<Self>) -> impl gpui::IntoElement {\n",
    );
    out.push_str("        if !self.__rml_loaded {\n");
    out.push_str("            self.__rml_loaded = true;\n");
    out.push_str("            rml_core::lifecycle::ILifecycle::on_loaded(self, cx);\n");
    out.push_str("        }\n");
    out.push_str("        use gpui::{ParentElement, InteractiveElement, StatefulInteractiveElement, IntoElement, Styled};\n");
    out.push_str("        use rml_ui::{ButtonVariants, Disableable, Sizable, Selectable, StyledExt};\n");
    out.push_str("        use rml::runtime::event_flow::convert as rml_convert;\n");

    let mut id_counter: usize = 0;
    let empty: Vec<String> = Vec::new();

    let (slot_left, slot_right, slot_bottom, body_children) = if matches!(shell, ShellWrap::Tab) {
        partition_tab_slot_children(&elem.children)
    } else {
        (None, None, None, elem.children.clone())
    };

    let body = if body_children.is_empty() {
        "gpui::div()".to_string()
    } else if body_children.len() == 1 {
        let (code, _) = gen_node(&body_children[0], ctx, 0, &mut id_counter, &empty)?;
        code
    } else {
        let mut code = String::from("gpui::div()");
        for child in &body_children {
            let (child_code, _) = gen_node(child, ctx, 0, &mut id_counter, &empty)?;
            code.push_str(&format!("\n            .child({})", child_code));
        }
        code
    };

    let slot_left_code = slot_left
        .as_ref()
        .map(|node| gen_node(node, ctx, 0, &mut id_counter, &empty).map(|(c, _)| c))
        .transpose()?;
    let slot_right_code = slot_right
        .as_ref()
        .map(|node| gen_node(node, ctx, 0, &mut id_counter, &empty).map(|(c, _)| c))
        .transpose()?;
    let slot_bottom_code = slot_bottom
        .as_ref()
        .map(|node| gen_node(node, ctx, 0, &mut id_counter, &empty).map(|(c, _)| c))
        .transpose()?;

    let final_body = match shell {
        ShellWrap::Modern => gen_modern_window_wrapper(elem, ctx, &body)?,
        ShellWrap::Tab => gen_tab_window_wrapper(
            elem,
            ctx,
            &body,
            slot_left_code.as_deref(),
            slot_right_code.as_deref(),
            slot_bottom_code.as_deref(),
        )?,
        ShellWrap::None => body,
    };

    out.push_str(&format!("        {}\n", final_body));
    out.push_str("    }\n");
    out.push_str("}\n");

    Ok(out)
}

/// 为 `<modern_window>` 根元素生成 ModernWindowShell 包裹代码
///
/// 生成形如：
/// ```text
/// rml_ui::ModernWindowShell::new()
///     .title(self.title().to_string())
///     .menu(self.menu_items().clone())
///     .status_bar(self.status_items().clone())
///     .child(<children>)
/// ```
///
/// - title 复用 IWindow::title()，不重复定义
/// - menu/status_bar 从根元素 Attribute::Bind 提取，使用表达式解析器处理 computed 方法
fn gen_modern_window_wrapper(
    elem: &Element,
    ctx: &CodegenCtx,
    children_body: &str,
) -> Result<String, CodegenError> {
    let computed: Vec<&str> = ctx.computed_methods.iter().map(|s| s.as_str()).collect();
    let empty: Vec<&str> = Vec::new();

    let mut code = String::from("rml_ui::ModernWindowShell::new()");

    // title 复用 IWindow::title()，消除根元素 title 属性的重复定义
    code.push_str(".title(self.title().to_string())");

    // menu/status_bar/icon 从根元素 bind 属性提取
    for attr in &elem.attributes {
        if let Attribute::Bind { name, expr } = attr {
            match name.as_str() {
                "menu" | "status_bar" => {
                    // menu/status_bar 是 Vec<T>，需要 .clone()
                    let rust_expr = match expr::parse(expr) {
                        Ok(expr::Expr::Field(field_name))
                            if computed.iter().any(|c| *c == field_name.as_str()) =>
                        {
                            format!("self.{}()", field_name)
                        }
                        Ok(parsed) => expr::to_rust_code_with_ctx(&parsed, &empty),
                        Err(_) => {
                            let trimmed = expr.trim();
                            if computed.iter().any(|c| *c == trimmed) {
                                format!("self.{}()", trimmed)
                            } else {
                                format!("self.{}", trimmed)
                            }
                        }
                    };
                    match name.as_str() {
                        "menu" => code.push_str(&format!(".menu({}.clone())", rust_expr)),
                        "status_bar" => {
                            code.push_str(&format!(".status_bar({}.clone())", rust_expr))
                        }
                        _ => {}
                    }
                }
                "icon" => {
                    // icon 是 IconName（Copy），支持三种形式：
                    //   icon={IconName::Frame}     → 直接枚举值（expr 解析器不支持 :: 路径，原样输出）
                    //   icon={self.app_icon}      → 字段引用
                    //   icon={app_icon}            → computed 方法（如果 app_icon 在 computed_methods 中）
                    let rust_expr = match expr::parse(expr) {
                        Ok(expr::Expr::Field(field_name))
                            if computed.iter().any(|c| *c == field_name.as_str()) =>
                        {
                            format!("self.{}()", field_name)
                        }
                        Ok(parsed) => expr::to_rust_code_with_ctx(&parsed, &empty),
                        Err(_) => {
                            // 解析失败：原样输出（支持 IconName::Frame 这类路径表达式）
                            expr.trim().to_string()
                        }
                    };
                    code.push_str(&format!(".icon(rml_ui::{})", rust_expr));
                }
                _ => {}
            }
        }
    }

    code.push_str(&format!(".child({})", children_body));
    code.push_str(".window_controls(self.window_controls())");
    Ok(code)
}

/// 将 `<tab_window>` 子节点拆分为插槽与主内容
fn partition_tab_slot_children(
    children: &[Node],
) -> (Option<Node>, Option<Node>, Option<Node>, Vec<Node>) {
    let mut slot_left = None;
    let mut slot_right = None;
    let mut slot_bottom = None;
    let mut body = Vec::new();

    for child in children {
        if let Node::Element(elem) = child {
            match elem.tag.as_str() {
                "slot_left" => {
                    slot_left = slot_element_content(elem);
                    continue;
                }
                "slot_right" => {
                    slot_right = slot_element_content(elem);
                    continue;
                }
                "slot_bottom" => {
                    slot_bottom = slot_element_content(elem);
                    continue;
                }
                _ => {}
            }
        }
        body.push(child.clone());
    }

    (slot_left, slot_right, slot_bottom, body)
}

/// 取插槽包装元素的内部内容（单子节点直接 unwrap，多子节点包 div）
fn slot_element_content(elem: &Element) -> Option<Node> {
    match elem.children.len() {
        0 => None,
        1 => Some(elem.children[0].clone()),
        _ => Some(Node::Element(Element {
            tag: "div".into(),
            attributes: vec![],
            directives: vec![],
            children: elem.children.clone(),
        })),
    }
}

/// 从根 `<tab_window>` 的 bind/event 属性生成 `TabWindowShell` 包裹代码
fn gen_tab_window_wrapper(
    elem: &Element,
    ctx: &CodegenCtx,
    children_body: &str,
    slot_left: Option<&str>,
    slot_right: Option<&str>,
    slot_bottom: Option<&str>,
) -> Result<String, CodegenError> {
    let computed: Vec<&str> = ctx.computed_methods.iter().map(|s| s.as_str()).collect();
    let empty: Vec<&str> = Vec::new();

    let mut code = String::from("rml_ui::TabWindowShell::new()");
    code.push_str(".title(self.title().to_string())");

    for attr in &elem.attributes {
        match attr {
            Attribute::Bind { name, expr } => {
                if name == "icon" {
                    let rust_expr = match expr::parse(expr) {
                        Ok(expr::Expr::Field(field_name))
                            if computed.iter().any(|c| *c == field_name.as_str()) =>
                        {
                            format!("self.{}()", field_name)
                        }
                        Ok(parsed) => expr::to_rust_code_with_ctx(&parsed, &empty),
                        Err(_) => expr.trim().to_string(),
                    };
                    let icon_expr = if rust_expr.contains("IconName::") {
                        format!("rml_ui::{rust_expr}")
                    } else {
                        rust_expr
                    };
                    code.push_str(&format!(".icon({icon_expr})"));
                    continue;
                }
                let rust_expr = shell_bind_expr(expr, &computed, &empty);
                match name.as_str() {
                    "menu" => code.push_str(&format!(".menu({}.clone())", rust_expr)),
                    "status_bar" => code.push_str(&format!(".status_bar({}.clone())", rust_expr)),
                    "tabs" => code.push_str(&format!(".tabs({}.clone())", rust_expr)),
                    "selected_tab" => code.push_str(&format!(".selected_tab({})", rust_expr)),
                    "show_chrome" => code.push_str(&format!(".show_chrome({})", rust_expr)),
                    _ => {}
                }
            }
            Attribute::Event { name, handler } if name == "on_tab_click" => {
                let method = match handler {
                    EventHandler::Ident(m) | EventHandler::MethodName(m) => m.as_str(),
                    EventHandler::WithArgs(m, _) => m.as_str(),
                };
                code.push_str(&format!(
                    ".on_tab_click({{\n                    \
                     let weak = cx.weak_entity();\n                    \
                     move |index: usize, _window: &mut gpui::Window, app: &mut gpui::App| {{\n                        \
                     if let Some(entity) = weak.upgrade() {{\n                            \
                     entity.update(app, |this, cx| {{ this.{}(index, cx); }});\n                        \
                     }}\n                    }}\n                }})",
                    method
                ));
            }
            Attribute::Event { name, handler } if name == "on_chrome_toggle" => {
                let method = match handler {
                    EventHandler::Ident(m) | EventHandler::MethodName(m) => m.as_str(),
                    EventHandler::WithArgs(m, _) => m.as_str(),
                };
                code.push_str(&format!(
                    ".on_chrome_toggle({{\n                    \
                     let weak = cx.weak_entity();\n                    \
                     move |_window: &mut gpui::Window, app: &mut gpui::App| {{\n                        \
                     if let Some(entity) = weak.upgrade() {{\n                            \
                     entity.update(app, |this, cx| {{ this.{}(cx); }});\n                        \
                     }}\n                    }}\n                }})",
                    method
                ));
            }
            _ => {}
        }
    }

    if let Some(left) = slot_left {
        code.push_str(&format!(".slot_left(Some({left}))"));
    }
    if let Some(right) = slot_right {
        code.push_str(&format!(".slot_right(Some({right}))"));
    }
    if let Some(bottom) = slot_bottom {
        code.push_str(&format!(".slot_bottom(Some({bottom}))"));
    }

    code.push_str(&format!(".child({})", children_body));
    code.push_str(".window_controls(self.window_controls())");
    Ok(code)
}

/// 将 shell 根元素的 bind 表达式编译为 Rust 代码
fn shell_bind_expr(expr: &str, computed: &[&str], loop_vars: &[&str]) -> String {
    let trimmed = expr.trim();
    if computed.iter().any(|c| *c == trimmed) {
        return format!("self.{}()", trimmed);
    }
    match expr::parse(expr) {
        Ok(expr::Expr::Field(field_name)) if computed.iter().any(|c| *c == field_name.as_str()) => {
            format!("self.{}()", field_name)
        }
        Ok(parsed) => expr::to_rust_code_with_ctx(&parsed, loop_vars),
        Err(_) => {
            if computed.iter().any(|c| *c == trimmed) {
                format!("self.{}()", trimmed)
            } else {
                format!("self.{}", trimmed)
            }
        }
    }
}

/// 生成 IWindow 可选配置方法（left/top/startup/min_size/window_controls）
fn gen_window_extra_methods(
    left: Option<f32>,
    top: Option<f32>,
    startup: Option<&str>,
    min_width: Option<f32>,
    min_height: Option<f32>,
    elem: &Element,
) -> String {
    let mut out = String::new();

    if let Some(left) = left {
        out.push_str(&format!(
            "\n    fn left(&self) -> Option<gpui::Pixels> {{\n        Some(gpui::px({left:?}))\n    }}\n"
        ));
    }
    if let Some(top) = top {
        out.push_str(&format!(
            "\n    fn top(&self) -> Option<gpui::Pixels> {{\n        Some(gpui::px({top:?}))\n    }}\n"
        ));
    }
    if let Some(startup) = startup {
        let variant = match startup {
            "CenterScreen" | "center" | "center_screen" => {
                "rml_core::window::WindowStartupLocation::CenterScreen"
            }
            _ => "rml_core::window::WindowStartupLocation::Manual",
        };
        out.push_str(&format!(
            "\n    fn startup_location(&self) -> rml_core::window::WindowStartupLocation {{\n        {variant}\n    }}\n"
        ));
    }
    if min_width.is_some() || min_height.is_some() {
        let w = min_width.unwrap_or(0.0);
        let h = min_height.unwrap_or(0.0);
        out.push_str(&format!(
            "\n    fn min_size(&self) -> Option<gpui::Size<gpui::Pixels>> {{\n        Some(gpui::Size {{ width: gpui::px({w:?}), height: gpui::px({h:?}) }})\n    }}\n"
        ));
    }

    let minimize = extract_static_bool_attr(elem, "show_minimize").unwrap_or(true);
    let maximize = extract_static_bool_attr(elem, "show_maximize").unwrap_or(true);
    let close = extract_static_bool_attr(elem, "show_close").unwrap_or(true);
    if !minimize || !maximize || !close {
        out.push_str(&format!(
            "\n    fn window_controls(&self) -> rml_core::window::WindowControlButtons {{\n        \
             rml_core::window::WindowControlButtons {{ minimize: {minimize}, maximize: {maximize}, close: {close} }}\n    }}\n"
        ));
    }

    out
}

/// 从元素属性中提取静态布尔值
fn extract_static_bool_attr(elem: &Element, name: &str) -> Option<bool> {
    extract_static_attr(elem, name).map(|v| {
        matches!(
            v.as_str(),
            "true" | "1" | "yes" | "True" | "TRUE" | "Yes" | "YES"
        )
    })
}

/// 从元素属性中提取静态属性值
fn extract_static_attr(elem: &Element, name: &str) -> Option<String> {
    elem.attributes.iter().find_map(|attr| match attr {
        Attribute::Static { name: n, value } if n == name => Some(value.clone()),
        _ => None,
    })
}

/// codegen 结果：元素代码 + 是否为迭代器
///
/// 当 `is_iter` 为 true 时，代码是 `self.<iterable>.iter().map(|<item>| { <element> })`，
/// 父元素应使用 `.children(...)` 而非 `.child(...)` 传入。
pub type GenResult = (String, bool);

/// 为单个节点生成构建代码，返回 (代码, 是否迭代器)
///
/// `loop_vars` 是当前作用域内的 each 循环变量名列表，
/// 用于在 `{todo.text}` 这类插值中生成 `todo.text` 而非 `self.todo.text`。
pub fn gen_node(
    node: &Node,
    ctx: &CodegenCtx,
    depth: usize,
    id_counter: &mut usize,
    loop_vars: &[String],
) -> Result<GenResult, CodegenError> {
    let lv: Vec<&str> = loop_vars.iter().map(|s| s.as_str()).collect();
    let computed: Vec<&str> = ctx.computed_methods.iter().map(|s| s.as_str()).collect();
    match node {
        Node::Element(elem) => gen_element(elem, ctx, depth, id_counter, loop_vars),
        Node::Text(text) => Ok((format!("{:?}", text), false)),
        Node::Interpolation(expr_str) => {
            // 单个插值：{field} → format!("{}", self.field)
            // {count + 1} → format!("{}", (self.count + 1))（通过 expr 解析器）
            // {computed_name} → format!("{}", self.computed_name())（计算属性，加 ()）
            Ok((
                format!("format!(\"{{}}\", {})", gen_expr_code(expr_str, &lv, &computed)),
                false,
            ))
        }
        Node::MixedText(segments) => {
            Ok((gen_mixed_text(segments, &lv, &computed), false))
        }
    }
}

fn gen_element(
    elem: &Element,
    ctx: &CodegenCtx,
    depth: usize,
    id_counter: &mut usize,
    loop_vars: &[String],
) -> Result<GenResult, CodegenError> {
    let tag = &elem.tag;

    // 扩展组件（PascalCase）：路由到 gpui-component 构造器
    if tags::is_component(tag) {
        let code = comp::gen_component(elem, ctx, depth, id_counter, loop_vars)?;
        return Ok((code, false));
    }

    // model 指令：input/textarea 的双向绑定
    // 当 input/textarea 标签有 model 指令时，路由到 rml_ui::Input 组件
    let model_field = elem.directives.iter().find_map(|d| match d {
        Directive::Model(f) => Some(f.clone()),
        _ => None,
    });

    if model_field.is_some() && (tag == "input" || tag == "textarea") {
        let code = gen_model_input(elem, ctx, id_counter, model_field.unwrap())?;
        return Ok((code, false));
    }

    let builtin = tags::lookup(tag).ok_or_else(|| CodegenError {
        message: format!("unknown tag: <{}>", tag),
    })?;

    // 检查 each 指令：列表渲染
    let each_clause = elem.directives.iter().find_map(|d| match d {
        Directive::Each(c) => Some(c.clone()),
        _ => None,
    });

    // 构建当前作用域的循环变量集合。
    // each 指令所在的元素本身就在 each 作用域内，其属性和子节点都应使用扩展后的 loop_vars。
    let mut child_loop_vars: Vec<String> = loop_vars.to_vec();
    if let Some(clause) = &each_clause {
        child_loop_vars.push(clause.item.clone());
        if let Some(idx) = &clause.index {
            child_loop_vars.push(idx.clone());
        }
    }
    let lv: Vec<&str> = child_loop_vars.iter().map(|s| s.as_str()).collect();

    // 1. 生成元素构造调用
    let mut code = String::from(builtin.codegen_ctor());

    // 2. 检查 ref 指令：为元素生成稳定 ID，供 ElementRef 关联
    //    ref="name" → .id(("rml_ref", "name"))
    //    若元素同时有事件处理器，ref ID 优先（同时满足 Stateful 要求）
    let ref_name: Option<&str> = elem.directives.iter().find_map(|d| match d {
        Directive::Ref(name) => Some(name.as_str()),
        _ => None,
    });

    // 检查是否有事件处理器 —— 若有，必须先 .id() 使元素成为 Stateful<Div>
    let has_events = elem
        .attributes
        .iter()
        .any(|attr| matches!(attr, Attribute::Event { .. }));

    if let Some(name) = ref_name {
        // ref 指令：生成稳定字符串 ID（GPUI ElementId 支持 &'static str）
        // 用 "rml_ref:<name>" 格式，便于调试与 Runtime 关联
        code.push_str(&format!(".id({:?})", format!("rml_ref:{}", name)));
    } else if has_events {
        let id_val = *id_counter;
        *id_counter += 1;
        code.push_str(&format!(".id((\"rml_el\", {}usize))", id_val));
    }

    // 2b. 应用 CSS 样式（class/id 属性匹配全局样式表）
    if let Some(sheet) = &ctx.stylesheet {
        let style_code = apply_css_styles(elem, tag, sheet);
        if !style_code.is_empty() {
            code.push_str(&style_code);
        }
    }

    // 3. 应用静态属性与绑定属性（class/id/style 已由 CSS 或下方跳过处理）
    for attr in &elem.attributes {
        match attr {
            Attribute::Static { name, value } => {
                code.push_str(&apply_static_attr(name, value));
            }
            Attribute::Bind { name, expr } => {
                let computed: Vec<&str> = ctx.computed_methods.iter().map(|s| s.as_str()).collect();
                code.push_str(&apply_bind_attr(name, expr, &lv, &computed));
            }
            Attribute::Event { name, handler } => {
                code.push_str(&event::apply_event(name, handler, ctx));
            }
        }
    }

    // 4. 处理子节点（传入扩展后的 child_loop_vars）
    for child in &elem.children {
        let (child_code, is_iter) = gen_node(child, ctx, depth + 1, id_counter, &child_loop_vars)?;
        if is_iter {
            // each 指令生成的迭代器：用 .children() 传入
            code.push_str(&format!("\n            .children({})", child_code));
        } else {
            code.push_str(&format!("\n            .child({})", child_code));
        }
    }

    // 5. 处理 each 指令：将元素包装在迭代器中
    if let Some(clause) = each_clause {
        // 生成 self.<iterable>.iter().map(|<item>| { <element> })
        // 在 map 闭包内，迭代变量名不加 self. 前缀
        let iter_code = format!(
            "self.{}.iter().map(|{}| {{\n                {}\n            }})",
            clause.iterable, clause.item, code
        );
        return Ok((iter_code, true));
    }

    // 6. 处理 if/show 指令：条件渲染
    let cond: Option<String> = elem.directives.iter().find_map(|d| match d {
        Directive::If(c) => Some(c.clone()),
        Directive::Show(c) => Some(c.clone()),
        _ => None,
    });

    // 6b. 处理 once 指令：首次渲染后不更新
    //     Phase B-2：识别指令但不生成缓存代码（GPUI 元素类型不满足 Send+Sync，
    //     无法用 static OnceLock 缓存）。完整缓存实现需 ViewModel 级字段，
    //     留到 Phase B-3 配合 #[view] 宏自动生成 once 缓存字段。
    //     当前行为：once 元素每次渲染都重新计算，与普通元素一致。

    if let Some(cond) = cond {
        Ok((
            format!(
                "if self.{} {{ {}.into_any_element() }} else {{ gpui::Empty.into_any_element() }}",
                cond, code
            ),
            false,
        ))
    } else {
        Ok((code, false))
    }
}

/// 生成带 model 指令的 Input 组件双向绑定代码
///
/// `<input model={field} placeholder="..." />` 生成：
/// ```text
/// rml_ui::Input::new(&self.__rml_get_or_init_input_state("field", Some("..."), _window, cx))
///     .disabled(false)
/// ```
///
/// 正向绑定（VM→UI）和反向绑定（UI→VM）均由 `__rml_get_or_init_input_state` 内部处理：
/// - 正向：首次创建时 `set_value` 初始化 + 后续 render 时版本号对比触发 `set_value`
/// - 反向：`cx.subscribe` 订阅 `InputEvent::Change`，闭包内回写字段 + bump_version + notify
///
/// placeholder 仅支持静态字符串（`InputState::placeholder()` 是 builder 方法，仅创建时可调）。
fn gen_model_input(
    elem: &Element,
    _ctx: &CodegenCtx,
    _id_counter: &mut usize,
    field: String,
) -> Result<String, CodegenError> {
    // 提取静态 placeholder（传入 __rml_get_or_init_input_state，在 InputState::new 时设置）
    let placeholder = elem.attributes.iter().find_map(|attr| {
        if let Attribute::Static { name, value } = attr {
            if name == "placeholder" { Some(value.clone()) } else { None }
        } else { None }
    });
    let placeholder_arg = match placeholder {
        Some(p) => format!("Some({:?})", p),
        None => "None".to_string(),
    };

    // 构造 Input 组件，传引用给 Input::new（内部 clone Entity）
    let mut input_code = format!(
        "rml_ui::Input::new(&self.__rml_get_or_init_input_state({:?}, {}, _window, cx))",
        field, placeholder_arg
    );

    // 应用静态 disabled 属性（Input 有 .disabled() 方法）
    for attr in &elem.attributes {
        if let Attribute::Static { name, value } = attr {
            if name == "disabled" {
                let disabled_val = if value.eq_ignore_ascii_case("true") || value == "1" || value.is_empty() {
                    "true"
                } else {
                    "false"
                };
                input_code.push_str(&format!(".disabled({})", disabled_val));
            }
        }
    }

    // 校验失败 UI 表现：检查 __rml_field_errors，若 Some(msg) 则修改 Input 自身边框颜色 + tooltip
    // Phase B-3.3：直接对 Input 调用 .border_color()（Styled trait）覆盖主题色，
    // 避免 wrapper div 附加外层边框导致双层边框 / 间距错位。
    // wrapper div 仅承载 .id()（StatefulInteractiveElement 以支持 .tooltip()）+ .child()。
    let wrapper_id = format!("rml_input_err:{}", field);
    let code = format!(
        r#"{{
            let __rml_input = {input_code};
            let __rml_err: Option<gpui::SharedString> = self.__rml_field_errors.get({field:?}).and_then(|e| e.clone());
            if let Some(__rml_err_msg) = __rml_err {{
                // 直接修改 Input 自身边框颜色（覆盖主题色，Input 内部已 border_1()）
                let __rml_input = __rml_input.border_color(gpui::rgb(0xff0000));
                gpui::div()
                    .id({wrapper_id:?})
                    .child(__rml_input)
                    .tooltip(move |window, cx| rml_ui::Tooltip::new(__rml_err_msg.clone()).build(window, cx))
                    .into_any_element()
            }} else {{
                __rml_input.into_any_element()
            }}
        }}"#,
        input_code = input_code,
        field = field,
        wrapper_id = wrapper_id
    );

    Ok(code)
}

/// 生成正向值表达式：`self.field` → `gpui::SharedString`
///
/// 数字类型需 `to_string().into()`（SharedString: From<String>）；
/// String/SharedString 等直接 `.clone().into()`。
fn gen_field_value_expr(field: &str, ty: &str) -> String {
    match ty {
        "i32" | "u32" | "i64" | "u64" | "f32" | "f64" | "usize" | "isize" => {
            format!("self.{}.to_string().into()", field)
        }
        _ => format!("self.{}.clone().into()", field),
    }
}

/// 生成反向赋值代码块：`value: SharedString` → `this.field = ...`
///
/// 返回完整代码块（含 parse + 赋值 + 错误处理 + bump_version），调用方不再追加 bump_version。
///
/// **整数类型**（i32/u32/i64/u64/isize/usize）：
///   `match value.parse::<T>() { Ok(v) => { 赋值 + 清除错误 + bump }, Err(_) => { 设置错误 } }`
///   parse 失败时（类型不匹配 + 类型溢出）**不覆盖原值**，仅设置错误状态
/// **浮点类型**（f32/f64）：同上，错误消息为"请输入有效的数字"
/// **bool 类型**：`!value.is_empty()`（非空字符串视为 true），总是成功
/// **String/其他**：`value.to_string()`，总是成功
///
/// Phase B-3.2：当 `validation` 为 `Some` 且规则非空时，在 parse 成功后、赋值前生成规则校验链。
/// 任一规则失败 → 设置错误状态，不赋值、不 bump_version；全部通过 → 赋值 + 清除错误 + bump_version。
fn gen_field_assign_expr(
    field: &str,
    ty: &str,
    validation: Option<&crate::compiler::ValidationRuleSet>,
) -> String {
    // Phase B-3.3：优先级 1——IValidate 接口式校验
    if let Some(v) = validation {
        if let Some(validator_type) = &v.validator_type {
            return gen_field_assign_with_validator(field, ty, validator_type);
        }
    }
    // 优先级 2——规则式校验（原有逻辑）
    let rules = match validation {
        Some(v) if !v.rules.is_empty() => &v.rules,
        _ => return gen_field_assign_expr_default(field, ty),
    };
    let custom_msg = validation.and_then(|v| v.custom_message.as_deref());

    match ty {
        "i32" | "u32" | "i64" | "u64" | "isize" | "usize" | "f32" | "f64" => {
            gen_numeric_field_assign_with_validation(field, ty, rules, custom_msg)
        }
        // bool 类型忽略校验规则（语义不明确）
        "bool" => gen_field_assign_expr_default(field, ty),
        _ => gen_string_field_assign_with_validation(field, rules, custom_msg),
    }
}

/// IValidate 接口式校验生成（Phase B-3.3）
///
/// 为 `#[validate(MyValidator)]` 标注的字段生成调用 `IValidate::valid_with_view` 的代码。
/// codegen 通过 `MyValidator::default()` 构造实例（要求 `Default`），
/// 调用 `valid_with_view(value, this as &dyn Any)`（this 即视图结构体引用，支持跨字段校验）。
/// 通过 `message(&result)` 转换 `ValidResult` 为 `Option<SharedString>`：
/// - `None` → 校验通过：赋值 + 清除错误 + bump_version
/// - `Some(msg)` → 校验失败：仅设置错误状态（不赋值、不 bump_version）
///
/// **数字类型**：外层 `match value.parse::<T>()`，parse 失败仍走原默认错误消息
/// **String 类型**：直接调用 validator，无 parse 阶段
/// **bool 类型**：忽略 IValidate（语义不明确），回退默认逻辑
fn gen_field_assign_with_validator(field: &str, ty: &str, validator_type: &str) -> String {
    match ty {
        "i32" | "u32" | "i64" | "u64" | "isize" | "usize" | "f32" | "f64" => {
            let is_integer = matches!(ty, "i32" | "u32" | "i64" | "u64" | "isize" | "usize");
            let type_err = if is_integer { "请输入有效的整数" } else { "请输入有效的数字" };
            format!(
                r#"match value.parse::<{ty}>() {{
    Ok(v) => {{
        let __rml_validator = {validator_type}::default();
        let __rml_result = __rml_validator.valid_with_view(value.as_ref(), this as &dyn std::any::Any);
        if let Some(__rml_err_msg) = __rml_validator.message(&__rml_result) {{
            this.__rml_field_errors.insert({field:?}.to_string(), Some(__rml_err_msg));
        }} else {{
            this.{field} = v;
            this.__rml_field_errors.insert({field:?}.to_string(), None);
            this.__rml_bump_version({field:?});
        }}
    }}
    Err(_) => {{
        this.__rml_field_errors.insert({field:?}.to_string(), Some({type_err:?}.into()));
    }}
}}"#,
                ty = ty,
                validator_type = validator_type,
                field = field,
                type_err = type_err,
            )
        }
        // bool 类型忽略 IValidate（与规则式一致）
        "bool" => gen_field_assign_expr_default(field, ty),
        // String / SharedString / 其他
        _ => format!(
            r#"{{
    let __rml_value = value.to_string();
    let __rml_validator = {validator_type}::default();
    let __rml_result = __rml_validator.valid_with_view(&__rml_value, this as &dyn std::any::Any);
    if let Some(__rml_err_msg) = __rml_validator.message(&__rml_result) {{
        this.__rml_field_errors.insert({field:?}.to_string(), Some(__rml_err_msg));
    }} else {{
        this.{field} = __rml_value;
        this.__rml_field_errors.insert({field:?}.to_string(), None);
        this.__rml_bump_version({field:?});
    }}
}}"#,
            validator_type = validator_type,
            field = field,
        ),
    }
}

/// 无校验规则时的默认反向赋值逻辑（Phase B-3.1 实现，向后兼容）
fn gen_field_assign_expr_default(field: &str, ty: &str) -> String {
    match ty {
        "i32" | "u32" | "i64" | "u64" | "isize" | "usize" => format!(
            r#"match value.parse::<{ty}>() {{
                Ok(v) => {{
                    this.{field} = v;
                    this.__rml_field_errors.insert({field:?}.to_string(), None);
                    this.__rml_bump_version({field:?});
                }}
                Err(_) => {{
                    this.__rml_field_errors.insert({field:?}.to_string(), Some("请输入有效的整数".into()));
                }}
            }}"#,
            field = field,
            ty = ty
        ),
        "f32" | "f64" => format!(
            r#"match value.parse::<{ty}>() {{
                Ok(v) => {{
                    this.{field} = v;
                    this.__rml_field_errors.insert({field:?}.to_string(), None);
                    this.__rml_bump_version({field:?});
                }}
                Err(_) => {{
                    this.__rml_field_errors.insert({field:?}.to_string(), Some("请输入有效的数字".into()));
                }}
            }}"#,
            field = field,
            ty = ty
        ),
        "bool" => format!(
            r#"this.{field} = !value.is_empty();
            this.__rml_field_errors.insert({field:?}.to_string(), None);
            this.__rml_bump_version({field:?});"#,
            field = field
        ),
        _ => format!(
            r#"this.{field} = value.to_string();
            this.__rml_field_errors.insert({field:?}.to_string(), None);
            this.__rml_bump_version({field:?});"#,
            field = field
        ),
    }
}

/// 数字类型字段 + 校验规则：生成 parse + range/custom 校验链
///
/// 生成代码结构：
/// ```text
/// match value.parse::<T>() {
///     Ok(v) => {
///         if <range_check> {
///             this.<field>.__rml_field_errors.insert(<field>, Some("<msg>".into()));
///         } else if let Some(__rml_err) = Self::<custom>(&value) {
///             this.<field>.__rml_field_errors.insert(<field>, __rml_err);
///         } else {
///             this.<field> = v;
///             this.__rml_field_errors.insert(<field>, None);
///             this.__rml_bump_version(<field>);
///         }
///     }
///     Err(_) => {
///         this.__rml_field_errors.insert(<field>, Some("<type_err>".into()));
///     }
/// }
/// ```
fn gen_numeric_field_assign_with_validation(
    field: &str,
    ty: &str,
    rules: &[crate::compiler::ValidationRule],
    custom_msg: Option<&str>,
) -> String {
    let is_integer = matches!(ty, "i32" | "u32" | "i64" | "u64" | "isize" | "usize");
    let type_err = if is_integer { "请输入有效的整数" } else { "请输入有效的数字" };

    // 生成校验分支（if-else if 链）
    let mut branches = String::new();
    for rule in rules {
        match rule {
            crate::compiler::ValidationRule::Range { min, max } => {
                let condition = match (min, max) {
                    (Some(min), Some(max)) => format!("v < {min} || v > {max}"),
                    (Some(min), None) => format!("v < {min}"),
                    (None, Some(max)) => format!("v > {max}"),
                    (None, None) => continue, // 无约束，跳过
                };
                let msg = custom_msg
                    .unwrap_or("值不在有效范围内")
                    .replace("{min}", &min.map(|v| v.to_string()).unwrap_or_default())
                    .replace("{max}", &max.map(|v| v.to_string()).unwrap_or_default());
                // 简单消息：若 custom_msg 不含 {min}/{max} 占位符，用默认格式
                let final_msg = if custom_msg.is_some() {
                    msg
                } else {
                    match (min, max) {
                        (Some(min), Some(max)) => format!("值必须在 {}-{} 之间", *min as i64, *max as i64),
                        (Some(min), None) => format!("值必须 >= {}", *min as i64),
                        (None, Some(max)) => format!("值必须 <= {}", *max as i64),
                        (None, None) => "值不在有效范围内".to_string(),
                    }
                };
                branches.push_str(&format!(
                    r#"        if {condition} {{
            this.__rml_field_errors.insert({field:?}.to_string(), Some({msg:?}.into()));
        }} else "#,
                    condition = condition,
                    field = field,
                    msg = final_msg
                ));
            }
            crate::compiler::ValidationRule::Custom(fn_name) => {
                branches.push_str(&format!(
                    r#"if let Some(__rml_err) = Self::{fn_name}(value.as_ref()) {{
            this.__rml_field_errors.insert({field:?}.to_string(), __rml_err);
        }} else "#,
                    fn_name = fn_name,
                    field = field
                ));
            }
            // required/length/regex 对数字类型不适用，忽略
            _ => continue,
        }
    }

    // 校验全部分支后的成功路径
    branches.push_str(&format!(
        r#"{{
            this.{field} = v;
            this.__rml_field_errors.insert({field:?}.to_string(), None);
            this.__rml_bump_version({field:?});
        }}"#,
        field = field
    ));

    format!(
        r#"match value.parse::<{ty}>() {{
            Ok(v) => {{
        {branches}
            }}
            Err(_) => {{
                this.__rml_field_errors.insert({field:?}.to_string(), Some({type_err:?}.into()));
            }}
        }}"#,
        ty = ty,
        branches = branches,
        field = field,
        type_err = type_err
    )
}

/// String 类型字段 + 校验规则：生成 required/length/regex/custom 校验链
///
/// 生成代码结构：
/// ```text
/// {
///     let __rml_value = value.to_string();
///     if __rml_value.is_empty() {
///         this.__rml_field_errors.insert(<field>, Some("<msg>".into()));
///     } else if __rml_value.len() < N || __rml_value.len() > M {
///         this.__rml_field_errors.insert(<field>, Some("<msg>".into()));
///     } else if !<regex>.is_match(&__rml_value) {
///         this.__rml_field_errors.insert(<field>, Some("<msg>".into()));
///     } else if let Some(__rml_err) = Self::<custom>(&__rml_value) {
///         this.__rml_field_errors.insert(<field>, __rml_err);
///     } else {
///         this.<field> = __rml_value;
///         this.__rml_field_errors.insert(<field>, None);
///         this.__rml_bump_version(<field>);
///     }
/// }
/// ```
fn gen_string_field_assign_with_validation(
    field: &str,
    rules: &[crate::compiler::ValidationRule],
    custom_msg: Option<&str>,
) -> String {
    let mut branches = String::new();

    for rule in rules {
        match rule {
            crate::compiler::ValidationRule::Required => {
                let msg = custom_msg.unwrap_or("此项为必填");
                branches.push_str(&format!(
                    r#"        if __rml_value.is_empty() {{
            this.__rml_field_errors.insert({field:?}.to_string(), Some({msg:?}.into()));
        }} else "#,
                    field = field,
                    msg = msg
                ));
            }
            crate::compiler::ValidationRule::Length { min, max } => {
                let condition = match (min, max) {
                    (Some(min), Some(max)) => format!("__rml_value.len() < {min} || __rml_value.len() > {max}"),
                    (Some(min), None) => format!("__rml_value.len() < {min}"),
                    (None, Some(max)) => format!("__rml_value.len() > {max}"),
                    (None, None) => continue,
                };
                let final_msg = if custom_msg.is_some() {
                    custom_msg.unwrap_or("长度不合法").to_string()
                } else {
                    match (min, max) {
                        (Some(min), Some(max)) => format!("长度必须在 {}-{} 之间", min, max),
                        (Some(min), None) => format!("长度必须 >= {}", min),
                        (None, Some(max)) => format!("长度必须 <= {}", max),
                        (None, None) => "长度不合法".to_string(),
                    }
                };
                branches.push_str(&format!(
                    r#"if {condition} {{
            this.__rml_field_errors.insert({field:?}.to_string(), Some({msg:?}.into()));
        }} else "#,
                    condition = condition,
                    field = field,
                    msg = final_msg
                ));
            }
            crate::compiler::ValidationRule::Regex(pattern) => {
                let msg = custom_msg.unwrap_or("格式不正确");
                branches.push_str(&format!(
                    r#"if !rml::regex::Regex::new({pattern:?}).unwrap().is_match(&__rml_value) {{
            this.__rml_field_errors.insert({field:?}.to_string(), Some({msg:?}.into()));
        }} else "#,
                    pattern = pattern,
                    field = field,
                    msg = msg
                ));
            }
            crate::compiler::ValidationRule::Custom(fn_name) => {
                branches.push_str(&format!(
                    r#"if let Some(__rml_err) = Self::{fn_name}(&__rml_value) {{
            this.__rml_field_errors.insert({field:?}.to_string(), __rml_err);
        }} else "#,
                    fn_name = fn_name,
                    field = field
                ));
            }
            // range 对 String 类型不适用，忽略
            _ => continue,
        }
    }

    // 校验全部分支后的成功路径
    branches.push_str(&format!(
        r#"{{
            this.{field} = __rml_value;
            this.__rml_field_errors.insert({field:?}.to_string(), None);
            this.__rml_bump_version({field:?});
        }}"#,
        field = field
    ));

    format!(
        r#"{{
            let __rml_value = value.to_string();
        {branches}
        }}"#,
        branches = branches
    )
}

fn apply_static_attr(name: &str, value: &str) -> String {
    match name {
        // class/id/style 由 CSS 系统（apply_css_styles）或 inline style 处理，此处跳过
        "class" | "id" => String::new(),
        // ref 是指令（Directive::Ref），不会作为静态属性出现，此处防御性跳过
        "ref" => String::new(),
        // style 属性：inline 样式，直接解析并应用（优先级高于 class）
        "style" => apply_inline_style(value),
        // src/href 等 URL 属性跳过（Phase B-2 资源系统实现）
        "src" | "href" => String::new(),
        // type 属性（button/checkbox 等）跳过（Phase B-2 表单系统实现）
        "type" => String::new(),
        // 其他静态属性作为子文本节点（调试用）
        _ => format!(".child({:?})", format!("{}={}", name, value)),
    }
}

/// 从元素的 class/id 属性提取值，匹配 CSS 样式表，返回 GPUI 方法调用代码
fn apply_css_styles(elem: &Element, tag: &str, sheet: &css::StyleSheet) -> String {
    // 提取静态 class 值（支持 class="a b c"）
    let class_value: String = elem
        .attributes
        .iter()
        .find_map(|attr| match attr {
            Attribute::Static { name, value } if name == "class" => Some(value.clone()),
            _ => None,
        })
        .unwrap_or_default();

    // 提取静态 id 值
    let id_value: Option<&str> = elem
        .attributes
        .iter()
        .find_map(|attr| match attr {
            Attribute::Static { name, value } if name == "id" => Some(value.as_str()),
            _ => None,
        });

    if class_value.is_empty() && id_value.is_none() {
        return String::new();
    }

    css::styles_for_class(sheet, tag, &class_value, id_value)
}

/// 解析 inline style 属性（如 `style="padding: 10px; color: red;"`）
///
/// 简化实现：按 `;` 分割声明，用 CSS 解析器解析每个声明，映射为 GPUI 方法调用。
fn apply_inline_style(style_str: &str) -> String {
    // 包装成完整 CSS 规则让解析器处理：`* { <style> }`
    let wrapped = format!("* {{ {} }}", style_str);
    match css::parse(&wrapped) {
        Ok(sheet) => {
            if sheet.rules.is_empty() || sheet.rules[0].declarations.is_empty() {
                return String::new();
            }
            css::mapper::map_declarations(&sheet.rules[0].declarations, &sheet.variables)
        }
        Err(_) => String::new(),
    }
}

fn apply_bind_attr(name: &str, expr: &str, loop_vars: &[&str], computed: &[&str]) -> String {
    match name {
        // value 绑定：将字段值格式化为文本子节点
        "value" => format!(".child(format!(\"{{}}\", {}))", gen_expr_code(expr, loop_vars, computed)),
        // 动态 class/id 绑定：运行时才知道值，codegen 无法静态匹配 CSS
        // 留待 Phase B-4 运行时样式系统支持
        "class" | "id" | "style" => String::new(),
        // disabled/checked：用 .when() 控制元素状态（仅当 true 时生效）
        // 注：.when(false) 返回原元素不变，无法真正禁用 —— Phase B-2 修复
        "disabled" | "checked" | "readonly" => format!(".when({}, |el| el)", gen_expr_code(expr, loop_vars, computed)),
        // 其他绑定属性作为文本子节点（调试用）
        _ => format!(".child(format!(\"{{}}\", {}))", gen_expr_code(expr, loop_vars, computed)),
    }
}

fn gen_mixed_text(segments: &[TextSegment], loop_vars: &[&str], computed: &[&str]) -> String {
    // 构建 format! 调用
    let mut fmt_str = String::new();
    let mut args = Vec::new();
    for seg in segments {
        match seg {
            TextSegment::Literal(s) => {
                fmt_str.push_str(&s.replace('{', "{{").replace('}', "}}"));
            }
            TextSegment::Interpolation(expr) => {
                fmt_str.push_str("{}");
                args.push(gen_expr_code(expr, loop_vars, computed));
            }
        }
    }
    if args.is_empty() {
        format!("{:?}", fmt_str)
    } else {
        format!("format!({:?}, {})", fmt_str, args.join(", "))
    }
}

/// 把插值表达式字符串编译为 Rust 表达式字符串。
///
/// 调用 `expr::parse` 将 `{count + 1}` 这类表达式解析为 AST，
/// 再用 `expr::to_rust_code_with_ctx` 生成 `(self.count + 1)` 等 Rust 代码。
/// `loop_vars` 中的字段名不加 `self.` 前缀（each 循环变量）。
/// `computed` 中的标识符被视为计算属性方法，生成 `self.name()` 而非 `self.name`。
/// 解析失败时回退到旧的「单字段」行为（`self.<expr>`），保证向后兼容。
fn gen_expr_code(expr_str: &str, loop_vars: &[&str], computed: &[&str]) -> String {
    if let Some(code) = try_gen_i18n_call(expr_str, loop_vars, computed) {
        return code;
    }
    match expr::parse(expr_str) {
        Ok(expr::Expr::Field(name)) if computed.iter().any(|c| *c == name.as_str()) => {
            if loop_vars.iter().any(|v| *v == name) {
                format!("{}()", name)
            } else {
                format!("self.{}()", name)
            }
        }
        Ok(parsed) => expr::to_rust_code_with_ctx(&parsed, loop_vars),
        Err(_) => {
            let trimmed = expr_str.trim();
            if loop_vars.iter().any(|v| *v == trimmed) {
                trimmed.to_string()
            } else if computed.iter().any(|c| *c == trimmed) {
                format!("self.{}()", trimmed)
            } else {
                format!("self.{}", trimmed)
            }
        }
    }
}

/// `{t("key")}` → `cx.t("key")`
pub(crate) fn try_gen_i18n_call(expr_str: &str, loop_vars: &[&str], computed: &[&str]) -> Option<String> {
    let trimmed = expr_str.trim();
    if !trimmed.starts_with("t(") || !trimmed.ends_with(')') {
        return None;
    }
    let inner = trimmed[2..trimmed.len() - 1].trim();
    if inner.is_empty() {
        return None;
    }
    if (inner.starts_with('"') && inner.ends_with('"') && inner.len() >= 2)
        || (inner.starts_with('\'') && inner.ends_with('\'') && inner.len() >= 2)
    {
        let key = &inner[1..inner.len() - 1];
        return Some(format!("cx.t({key:?})"));
    }
    let key_expr = gen_expr_code(inner, loop_vars, computed);
    Some(format!("cx.t(&{key_expr})"))
}

